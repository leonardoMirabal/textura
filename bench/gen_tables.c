/* Textura: writes engines/tx_tables.c and tx_tables.h, the shared integer tables of the cores (host tool; float is
 * fine here). Each table is defined once (tx_tables.c) so the device keeps one copy in SRAM.
 *   make tx-tables     (regenerate; never hand-edit them) */
#include <math.h>
#include <stdio.h>

#define PULSE_N 64

static FILE *hdr;

static void row(FILE *f, const char *type, const char *name, const long *v, int n, int per)
{
    int i;
    fprintf(hdr, "extern const %s %s[%d];\n", type, name, n);
    fprintf(f, "TX_AUDIO_DATA const %s %s[%d] = {", type, name, n);
    for (i = 0; i < n; i++) fprintf(f, "%s%ld%s%s", i % per ? " " : "\n    ", v[i], type[1] == 'i' ? "u" : "", i < n - 1 ? "," : "");
    fprintf(f, "\n};\n\n");
}

int main(int argc, char **argv)
{
    long v[1024];
    int i;
    double lim = 32767.0;
    FILE *f = fopen(argc > 2 ? argv[2] : "engines/tx_tables.c", "w");
    hdr = fopen(argc > 1 ? argv[1] : "engines/tx_tables.h", "w");
    if (!f || !hdr) { perror("tx_tables"); return 1; }
    fprintf(hdr, "/* SPDX-License-Identifier: GPL-3.0-only */\n"
                 "/* Textura: shared tables of the cores. GENERATED by bench/gen_tables.c (make tx-tables): do not edit. */\n"
                 "#ifndef TX_TABLES_H\n#define TX_TABLES_H\n#include <stdint.h>\n\n");
    fprintf(f, "/* SPDX-License-Identifier: GPL-3.0-only */\n"
               "/* Textura: shared tables of the cores. GENERATED by bench/gen_tables.c (make tx-tables): do not edit. */\n"
               "#include \"tx_engine.h\"\n#include \"tx_tables.h\"\n\n");
    /* log2(1 + i/256), Q15 (TX_LOG2_FRAC[256] = 32768) */
    for (i = 0; i <= 256; i++) v[i] = lround(log2(1.0 + i / 256.0) * 32768.0);
    fprintf(f, "/* log2(1 + i/256) in Q15, i = 0..256 */\n");
    row(f, "uint16_t", "TX_LOG2_FRAC", v, 257, 12);
    /* 2^(i/256), Q30 (values 2^30 .. 2^31) */
    for (i = 0; i <= 256; i++) v[i] = (long)llround(pow(2.0, i / 256.0) * 1073741824.0);
    fprintf(f, "/* 2^(i/256) in Q30, i = 0..256 (2^30 .. 2^31) */\n");
    row(f, "uint32_t", "TX_EXP2_FRAC", v, 257, 8);
    /* quarter sine, Q15 */
    for (i = 0; i <= 256; i++) v[i] = lround(sin(i / 256.0 * M_PI / 2.0) * lim);
    fprintf(f, "/* sin(i/256 * pi/2) in Q15, i = 0..256 (a quarter period) */\n");
    row(f, "int16_t", "TX_QSIN", v, 257, 12);
    /* pulse shapes, PULSE_N + 1 points each (the last is the end value), Q15 */
    fprintf(hdr, "#define TX_PULSE_N %d                 /* points per pulse shape (+1 guard point) */\n", PULSE_N);
    for (i = 0; i <= PULSE_N; i++) {               /* Hertz contact force: sin^1.5 over the contact */
        double s = sin(M_PI * i / PULSE_N);
        v[i] = lround(pow(s < 0 ? 0 : s, 1.5) * lim);
    }
    fprintf(f, "/* contact force (Hertz-like): sin(pi t)^1.5 */\n");
    row(f, "int16_t", "TX_PULSE_HERTZ", v, PULSE_N + 1, 12);
    for (i = 0; i <= PULSE_N; i++) v[i] = lround(0.5 * (1.0 - cos(2.0 * M_PI * i / PULSE_N)) * lim);
    fprintf(f, "/* raised cosine: 0.5 (1 - cos(2 pi t)) */\n");
    row(f, "int16_t", "TX_PULSE_RCOS", v, PULSE_N + 1, 12);
    for (i = 0; i <= PULSE_N; i++) {               /* N-wave, smoothed: the derivative of a raised cosine, normalised */
        v[i] = lround(sin(2.0 * M_PI * i / PULSE_N) * lim);
    }
    fprintf(f, "/* smoothed N-wave (doublet): sin(2 pi t), the pressure of a short spark / crack */\n");
    row(f, "int16_t", "TX_PULSE_NWAVE", v, PULSE_N + 1, 12);
    for (i = 0; i <= PULSE_N; i++) {               /* click: fast attack, exponential decay to ~-60 dB, ends at 0 */
        double t = (double)i / PULSE_N, a = (1.0 - exp(-t * 40.0)) * exp(-t * 6.9);
        v[i] = i == PULSE_N ? 0 : lround(a / 0.9 * lim > lim ? lim : a / 0.9 * lim);
    }
    fprintf(f, "/* click: fast rise, exponential decay */\n");
    row(f, "int16_t", "TX_PULSE_CLICK", v, PULSE_N + 1, 12);
    /* constants */
    fprintf(hdr, "\n/* log2 of the phase increment (2^32 / fs) of A4 = 440 Hz, Q16 */\n#define TX_LOG2_INC_A4 %ld\n\n",
            lround((32.0 + log2(440.0 / 44100.0)) * 65536.0));
    fprintf(hdr, "/* ln 2 in Q12 */\n#define TX_LN2_Q12 %ld\n\n", lround(log(2.0) * 4096.0));
    fprintf(hdr, "#endif\n");
    fclose(f);
    fclose(hdr);
    return 0;
}
