/* Textura: writes engines/tx_fx_tables.c and tx_fx_tables.h, the effects' integer tables (host tool; float is fine
 * here). The formulas are Frodhes' tools/gen_fx_tables.py (our own), for the tables the effects use:
 *   make tx-fx-tables     (regenerate; never hand-edit them) */
#include <math.h>
#include <stdio.h>

#define FS 44100.0

static FILE *hdr, *src;

static void row(const char *type, const char *name, const long *v, int n, int per, const char *what)
{
    int i;
    fprintf(hdr, "extern const %s %s[%d];   /* %s */\n", type, name, n, what);
    fprintf(src, "/* %s */\nTX_AUDIO_DATA const %s %s[%d] = {", what, type, name, n);
    for (i = 0; i < n; i++) fprintf(src, "%s%ld%s%s", i % per ? " " : "\n    ", v[i], type[0] == 'u' ? "u" : "", i < n - 1 ? "," : "");
    fprintf(src, "\n};\n\n");
}

/* the drive's level trim: the loudness its saturation adds (measured in Frodhes, LUFS) taken back */
static double drv_rise(int v)
{
    static const double A[16][2] = {{0, 0.0}, {16, -0.71}, {24, -0.48}, {32, 0.11}, {40, 0.9}, {48, 1.77}, {56, 2.62},
        {64, 3.39}, {72, 4.04}, {80, 4.55}, {88, 4.91}, {96, 5.11}, {104, 5.15}, {112, 5.03}, {120, 4.76}, {127, 4.39}};
    int i;
    for (i = 0; i < 15; i++)
        if (A[i][0] <= v && v <= A[i + 1][0]) return A[i][1] + (A[i + 1][1] - A[i][1]) * (v - A[i][0]) / (A[i + 1][0] - A[i][0]);
    return A[15][1];
}

int main(int argc, char **argv)
{
    long v[1100];
    int i;
    hdr = fopen(argc > 1 ? argv[1] : "engines/tx_fx_tables.h", "w");
    src = fopen(argc > 2 ? argv[2] : "engines/tx_fx_tables.c", "w");
    if (!hdr || !src) { perror("tx_fx_tables"); return 1; }
    fprintf(hdr, "/* SPDX-License-Identifier: GPL-3.0-only */\n/* Textura effects: tables. GENERATED by bench/gen_fx_tables.c"
                 " (make tx-fx-tables): do not edit. */\n#ifndef TX_FX_TABLES_H\n#define TX_FX_TABLES_H\n#include <stdint.h>\n\n");
    fprintf(src, "/* SPDX-License-Identifier: GPL-3.0-only */\n/* Textura effects: tables. GENERATED by bench/gen_fx_tables.c"
                 " (make tx-fx-tables): do not edit. */\n#include \"tx_engine.h\"\n#include \"tx_fx_tables.h\"\n\n");
    for (i = 0; i < 1025; i++) v[i] = lround(32767 * sin(2 * M_PI * i / 1024));
    row("int16_t", "TX_FX_SINE", v, 1025, 16, "Q15 sine over one cycle (+ guard)");
    for (i = 0; i < 257; i++) v[i] = lround(32767 * tanh(-4 + i / 32.0));
    row("int16_t", "TX_FX_TANH", v, 257, 16, "Q15 tanh over [-4, 4) in steps of 1/32 (the soft clip)");
    for (i = 0; i < 128; i++) v[i] = lround(0.5 * pow(24, i / 127.0) / FS * 4294967296.0);
    row("uint32_t", "TX_FX_LFO_INC", v, 128, 8, "the LFO's Q32 phase step a sample: 0.5 .. 12 Hz, exponential");
    for (i = 0; i < 128; i++) v[i] = lround(32767 * pow(10, (-0.0896 * i - (i > 16 ? drv_rise(i) : 0.0)) / 20));
    row("uint16_t", "TX_FX_DRV_LVL", v, 128, 12, "the drive's make-up trim (Q15): level-neutral over AMOUNT");
    for (i = 0; i < 258; i++) v[i] = lround(tan(M_PI * 30 * pow(16000 / 30.0, (i < 256 ? i : 256) / 256.0) / FS) * 16777216.0);
    row("uint32_t", "TX_FX_FL_G", v, 258, 8, "the filter's g = tan(pi fc / fs), Q24, fc 30 Hz .. 16 kHz (log, 256 steps + guards)");
    for (i = 0; i < 128; i++) v[i] = lround(16777216.0 / (0.7071 * pow(20 / 0.7071, i / 127.0)));
    row("uint32_t", "TX_FX_FL_K", v, 128, 8, "the filter's damping k = 1 / Q, Q24: Q 0.707 .. 20 (exponential)");
    fprintf(hdr, "\n#endif\n");
    fclose(hdr); fclose(src);
    return 0;
}
