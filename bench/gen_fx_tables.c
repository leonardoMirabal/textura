/* Textura: writes engines/tx_fx_tables.c and tx_fx_tables.h, the effects' integer tables (host tool; float is fine
 * here). The formulas are Frodhes' tools/gen_fx_tables.py (our own), for the tables the effects use:
 *   make tx-fx-tables     (regenerate; never hand-edit them) */
#include <math.h>
#include <stdio.h>
#include "../engines/tx_fx_gd_len.h"

#define FS 44100.0

static FILE *hdr, *src;

/* the reverb kernels' one-poles at the full rate: for a half-rate pole p (the designs' own, at 22.05 kHz), the pole at
 * 44.1 kHz whose response (DC gain 1) is closest to it over 60 Hz .. 11 kHz in log magnitude, every octave alike (a
 * least-squares fit; golden-section search). Matching the corner instead (sqrt p) leaves the top damped harder: the
 * INFINITE tails 5-12 % shorter */
static double pole_err(double p2, double p1)
{
    double e = 0;
    int k;
    for (k = 0; k < 300; k++) {
        double f = 60.0 * pow(11025.0 / 60.0, k / 299.0), w1 = 2 * M_PI * f / 22050.0, w2 = 2 * M_PI * f / 44100.0;
        double h1 = log((1 - p1) / sqrt(1 - 2 * p1 * cos(w1) + p1 * p1));
        double h2 = log((1 - p2) / sqrt(1 - 2 * p2 * cos(w2) + p2 * p2));
        e += (h2 - h1) * (h2 - h1);
    }
    return e;
}
static double pole_fit(double p1)
{
    double a = 0, b = 0.99999, g = (sqrt(5.0) - 1) / 2, c = b - g * (b - a), d = a + g * (b - a);
    while (b - a > 1e-10) {
        if (pole_err(c, p1) < pole_err(d, p1)) b = d; else a = c;
        c = b - g * (b - a), d = a + g * (b - a);
    }
    return (a + b) / 2;
}

static void row(const char *type, const char *name, const long *v, int n, int per, const char *what)
{
    int i;
    fprintf(hdr, "extern const %s %s[%d];   /* %s */\n", type, name, n, what);
    fprintf(src, "/* %s */\nTX_AUDIO_DATA const %s %s[%d] = {", what, type, name, n);
    for (i = 0; i < n; i++) fprintf(src, "%s%ld%s%s", i % per ? " " : "\n    ", v[i], type[0] == 'u' ? "u" : "", i < n - 1 ? "," : "");
    fprintf(src, "\n};\n\n");
}

/* the drive's level trim: the loudness its saturation adds (measured in Frodhes, LUFS) taken back */
static double drv_rise(int v)
{
    static const double A[16][2] = {{0, 0.0}, {16, -0.71}, {24, -0.48}, {32, 0.11}, {40, 0.9}, {48, 1.77}, {56, 2.62},
        {64, 3.39}, {72, 4.04}, {80, 4.55}, {88, 4.91}, {96, 5.11}, {104, 5.15}, {112, 5.03}, {120, 4.76}, {127, 4.39}};
    int i;
    for (i = 0; i < 15; i++)
        if (A[i][0] <= v && v <= A[i + 1][0]) return A[i][1] + (A[i + 1][1] - A[i][1]) * (v - A[i][0]) / (A[i + 1][0] - A[i][0]);
    return A[15][1];
}

int main(int argc, char **argv)
{
    long v[1100];
    char what[120];
    int i;
    hdr = fopen(argc > 1 ? argv[1] : "engines/tx_fx_tables.h", "w");
    src = fopen(argc > 2 ? argv[2] : "engines/tx_fx_tables.c", "w");
    if (!hdr || !src) { perror("tx_fx_tables"); return 1; }
    fprintf(hdr, "/* SPDX-License-Identifier: GPL-3.0-only */\n/* Textura effects: tables. GENERATED by bench/gen_fx_tables.c"
                 " (make tx-fx-tables): do not edit. */\n#ifndef TX_FX_TABLES_H\n#define TX_FX_TABLES_H\n#include <stdint.h>\n\n");
    fprintf(src, "/* SPDX-License-Identifier: GPL-3.0-only */\n/* Textura effects: tables. GENERATED by bench/gen_fx_tables.c"
                 " (make tx-fx-tables): do not edit. */\n#include \"tx_engine.h\"\n#include \"tx_fx_tables.h\"\n\n");
    for (i = 0; i < 1025; i++) v[i] = lround(32767 * sin(2 * M_PI * i / 1024));
    row("int16_t", "TX_FX_SINE", v, 1025, 16, "Q15 sine over one cycle (+ guard)");
    for (i = 0; i < 257; i++) v[i] = lround(32767 * tanh(-4 + i / 32.0));
    row("int16_t", "TX_FX_TANH", v, 257, 16, "Q15 tanh over [-4, 4) in steps of 1/32 (the soft clip)");
    for (i = 0; i < 128; i++) v[i] = lround(0.5 * pow(24, i / 127.0) / FS * 4294967296.0);
    row("uint32_t", "TX_FX_LFO_INC", v, 128, 8, "the LFO's Q32 phase step a sample: 0.5 .. 12 Hz, exponential");
    for (i = 0; i < 128; i++) v[i] = lround(32767 * pow(10, (-0.0896 * i - (i > 16 ? drv_rise(i) : 0.0)) / 20));
    row("uint16_t", "TX_FX_DRV_LVL", v, 128, 12, "the drive's make-up trim (Q15): level-neutral over AMOUNT");
    for (i = 0; i < 258; i++) v[i] = lround(tan(M_PI * 30 * pow(16000 / 30.0, (i < 256 ? i : 256) / 256.0) / FS) * 16777216.0);
    row("uint32_t", "TX_FX_FL_G", v, 258, 8, "the filter's g = tan(pi fc / fs), Q24, fc 30 Hz .. 16 kHz (log, 256 steps + guards)");
    for (i = 0; i < 128; i++) v[i] = lround(16777216.0 / (0.7071 * pow(20 / 0.7071, i / 127.0)));
    row("uint32_t", "TX_FX_FL_K", v, 128, 8, "the filter's damping k = 1 / Q, Q24: Q 0.707 .. 20 (exponential)");
    for (i = 0; i < 1025; i++) v[i] = lround(32767 * 0.5 * (1 - cos(2 * M_PI * i / 1024)));
    row("int16_t", "TX_FX_HANN", v, 1025, 16, "Q15 Hann window over one grain (+ guard): exact zeros at both ends");
    for (i = 0; i <= (int)TX_GD_TIME_MAX; i++) {     /* (0 .. 127 as before; on, the same steps, cut at the top) */
        double t = 0.020 * FS * pow(TX_GD_TOP0 / (0.020 * FS), i / 127.0);
        if (i == (int)TX_GD_TIME_MAX - 1 && lround(t) >= (long)TX_GD_TOP) {
            fprintf(stderr, "gen_fx_tables: TX_GD_TIME_MAX %u is past the top (make it smaller)\n", TX_GD_TIME_MAX);
            return 1;
        }
        if (i == (int)TX_GD_TIME_MAX && lround(t) < (long)TX_GD_TOP) {
            fprintf(stderr, "gen_fx_tables: TX_GD_TIME_MAX %u does not reach the top (make it larger)\n", TX_GD_TIME_MAX);
            return 1;
        }
        v[i] = lround(t) > (long)TX_GD_TOP ? (long)TX_GD_TOP : lround(t);
    }
    snprintf(what, sizeof what, "the grain delay's TIME in samples: 20 ms .. %.2f s at 127 .. %.2f s at %u (exponential; the line's top)",
             TX_GD_TOP0 / FS, TX_GD_TOP / FS, TX_GD_TIME_MAX);
    row("uint32_t", "TX_FX_GD_TIME", v, (int)TX_GD_TIME_MAX + 1, 8, what);
    for (i = 0; i < 128; i++) v[i] = lround(4294967296.0 / (0.020 * pow(25.0, i / 127.0) * FS));
    row("uint32_t", "TX_FX_GD_SIZE", v, 128, 8, "the grains' clock, Q32 phase a sample: a grain 20 .. 500 ms long (exponential)");
    for (i = 0; i < 25; i++) v[i] = lround(65536.0 * pow(2.0, (i - 12) / 12.0));
    row("uint32_t", "TX_FX_GD_PITCH", v, 25, 8, "the grains' rate, Q16, for -12 .. +12 semitones");
    for (i = 0; i < 128; i++) v[i] = lround(32768.0 * (1 - exp(-2 * M_PI * 400 * pow(40.0, i / 127.0) / FS)));
    row("uint16_t", "TX_FX_GD_TONE", v, 128, 12, "the feedback's one-pole low-pass, Q15: 400 Hz .. 16 kHz (exponential)");
    for (i = 0; i < 128; i++) {   /* FEEDBACK: 0 .. 64 as before (i x 258); then a pass's gain in dB, -5.98 at 64 rising as
                                   * ((110 - i) / 46)^1.5 to 0 dB at 110 (endless), on to +2.5 dB at 127 (it runs away) */
        double db64 = 20 * log10(64 * 258 / 32768.0);
        double db = i <= 64 ? 0 : i <= 110 ? db64 * pow((110 - i) / 46.0, 1.5) : 2.5 * (i - 110) / 17.0;
        v[i] = i <= 64 ? i * 258 : lround(32768.0 * pow(10.0, db / 20));
    }
    row("uint16_t", "TX_FX_GD_FB", v, 128, 12, "the grain delay's FEEDBACK, Q15: x 258 to 64, 1.0 at 110, +2.5 dB at 127 (dB a pass)");
    for (i = 0; i < 65; i++) v[i] = i < 64 ? lround(32768.0 * pole_fit(i / 64.0)) : 32767;
    for (i = 0; i < 65; i++) v[i] = v[i] > 32767 ? 32767 : v[i];
    row("int16_t", "TX_FX_RV_POLE", v, 65, 13, "the reverb's one-pole poles at 44.1 kHz for the designs' half-rate poles, Q15 (in steps of 1/64)");
    fprintf(hdr, "\n#endif\n");
    fclose(hdr); fclose(src);
    return 0;
}
