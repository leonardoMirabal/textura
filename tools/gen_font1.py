"""FONT_S at one bit a pixel: firmware/gen/felucca_font1.h from firmware/gen/felucca_font.h (Frodhes' gen_font.py
output, make fw-fonts). Terminus is a bitmap font: every nibble there is 0 or 15, so one bit holds it exactly (gfx.c
cv_text draws 15 for a set bit: the same pixels). Each glyph's rows run on bit by bit (h rows of bw bits, MSB first);
glyphs with the same bits share them.

  gen_font1.py           write felucca_font1.h
  gen_font1.py --check   fail (exit 1) if it is not what felucca_font.h gives"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "firmware" / "gen" / "felucca_font.h"
OUT = ROOT / "firmware" / "gen" / "felucca_font1.h"


def arr(t, name):
    m = re.search(name + r"\[\d+\] = \{(.*?)\};", t, re.S)
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(1))]


def build():
    t = SRC.read_text()
    h, pad, first, last = (int(x) for x in re.search(
        r"felucca_font_t FONT_S = \{ (\d+), (\d+), (\d+), (\d+),", t).groups())
    data, off, adv, bw = arr(t, "FONT_S_DATA"), arr(t, "FONT_S_OFF"), arr(t, "FONT_S_ADV"), arr(t, "FONT_S_BW")
    bits, boff, seen = [], [], {}
    for g in range(len(off)):
        w, bpr, row = bw[g], (bw[g] + 1) // 2, []
        for y in range(h):
            for x in range(w):
                b = data[off[g] + y * bpr + x // 2] if w else 0
                v = (b & 15) if x & 1 else (b >> 4)
                if v not in (0, 15):
                    sys.exit(f"gen_font1: glyph {g} has the alpha {v}: not a bitmap font")
                row.append(1 if v else 0)
        key = tuple(row)
        if key not in seen:
            seen[key] = len(bits)
            bits += row
        boff.append(seen[key])
    bits += [0] * (-len(bits) % 8)
    by = [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    assert len(bits) < 65536
    lines = ["/* generated by tools/gen_font1.py from felucca_font.h (Frodhes' gen_font.py, ter-u16n.bdf): FONT_S at one",
             f" * bit a pixel, each glyph's {h} rows of its width bit by bit (MSB first); off = the glyph's first bit */",
             "#pragma once", "#include <stdint.h>", "",
             f"static const uint8_t FONT_S_DATA[{len(by)}] = {{"]
    for i in range(0, len(by), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in by[i:i + 16]) + ",")
    lines += ["};",
              f"static const uint16_t FONT_S_OFF[{len(boff)}] = {{{', '.join(map(str, boff))}}};",
              f"static const uint8_t FONT_S_ADV[{len(adv)}] = {{{', '.join(map(str, adv))}}};",
              f"static const uint8_t FONT_S_BW[{len(bw)}] = {{{', '.join(map(str, bw))}}};",
              f"static const felucca_font_t FONT_S = {{ {h}, {pad}, {first}, {last}, FONT_S_ADV, FONT_S_BW, FONT_S_OFF, "
              "FONT_S_DATA };", ""]
    return "\n".join(lines)


def main():
    s = build()
    if "--check" in sys.argv[1:]:
        if OUT.read_text() != s:
            sys.exit("gen_font1: firmware/gen/felucca_font1.h is not what felucca_font.h gives (run tools/gen_font1.py)")
        return
    OUT.write_text(s)
    print(f"gen_font1: {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
