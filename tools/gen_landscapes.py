"""The firmware's landscapes (firmware/src/landscapes.h) from the audition player's (audition/app.js), so the two
never drift: the player is the development view, the firmware plays the same sounds on the same keys.

  gen_landscapes.py           write firmware/src/landscapes.h
  gen_landscapes.py --check   fail (exit 1) if firmware/src/landscapes.h is not what app.js gives (make fw-test)

Read from app.js: FAMILIES (each landscape's sounds: a SOURCE preset and TYPE, or "#engine" a classic engine, or
[name, "#engine"] a classic engine under a name of its own),
QUICK (a classic engine's activity map: its parameters from C4 to C6, a one-shot engine's gap between presses, a turned
engine's gap between turns, a caller's call length, a chord held, a measured curve),
COUNT_V, COUNT_N, NCNT, NACT (the HOW MANY and HOW ACTIVE keys)."""
import ast
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "audition" / "app.js"
OUT = ROOT / "firmware" / "src" / "landscapes.h"


def block(src, start, end):
    i = src.index(start) + len(start)
    return src[i:src.index(end, i)]


def families(src):
    t = "[" + block(src, "const FAMILIES = [", "\n];") + "]"
    t = re.sub(r"\[([^\[\]]*)\]\.map\(n => \[n, n, 0\]\)",
               lambda m: repr([[n, n, 0] for n in ast.literal_eval("[" + m.group(1) + "]")]), t)
    return ast.literal_eval(t)


def quick(src):
    t = "{" + block(src, "const QUICK = {", "\n};") + "}"
    t = re.sub(r"(?m)([{,]\s*)([a-z_]+):", r'\1"\2":', t)
    return ast.literal_eval(t)


def level_db(src):
    return ast.literal_eval("{" + block(src, "const LEVEL_DB = {", "\n};") + "}")


def trim_q12(db):
    return round(4096 * 10 ** (db / 20))   # (as app.js trimQ12: Math.round)


def const(src, name):
    return ast.literal_eval(re.search(r"\b" + name + r" = ([^,;\n]+(?:\[[^\]]*\])?)", src).group(1))


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    src = APP.read_text()
    fams, qk, lv = families(src), quick(src), level_db(src)
    count_v = ast.literal_eval(re.search(r"const COUNT_V = (\[[^\]]*\])", src).group(1))
    count_n = ast.literal_eval(re.search(r"COUNT_N = (\[[^\]]*\])", src).group(1))
    ncnt = int(re.search(r"NCNT = (\d+)", src).group(1))
    nact = int(re.search(r"NACT = (\d+)", src).group(1))
    nmax = max(len(s) for _, s in fams)
    assert nmax <= 16, "a landscape holds 16 sounds at most (presets.c: the sound in 4 bits)"
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* generated by tools/gen_landscapes.py from audition/app.js (FAMILIES, LEVEL_DB, QUICK, COUNT_V, COUNT_N, NCNT, NACT): do not edit.",
           " * make fw-landscapes writes it again; make fw-test fails when it no longer matches app.js. */",
           "#ifndef TX_LANDSCAPES_H", "#define TX_LANDSCAPES_H", "#include <stdint.h>", "",
           f"#define LS_N {len(fams)}u                     /* landscapes */",
           f"#define LS_SND_MAX {nmax}u               /* sounds in a landscape at most (16: presets.c keeps one in 4 bits) */",
           f"#define LS_NCNT {ncnt}u                  /* HOW MANY: off, then 1, 2, 4, 10, 19, 32 (the source's COUNT: LS_COUNT_V; shown: LS_COUNT_N) */",
           f"#define LS_NACT {nact}u                  /* HOW ACTIVE: rare .. busy */",
           "typedef struct { const char *name, *src; uint8_t type, eng; uint16_t trim; } ls_sound_t;   /* eng 1: src is a classic",
           " * engine's name; trim: the sound's own level, Q12 (4096 = 0 dB: LEVEL_DB) */",
           "typedef struct { const char *name; uint8_t n; ls_sound_t s[LS_SND_MAX]; } ls_family_t;",
           "static const ls_family_t LS[LS_N] = {"]
    for name, sounds in fams:
        items = []
        for snd in sounds:
            t = trim_q12(lv.get(name, {}).get(snd[0].lstrip("#"), 0))
            if snd[0].startswith("#"):
                items.append(f"{{{c_str(snd[0][1:])}, {c_str(snd[0][1:])}, 0, 1, {t}}}")
            elif len(snd) > 1 and snd[1].startswith("#"):          # [name, "#engine"]: a classic engine, named
                items.append(f"{{{c_str(snd[0])}, {c_str(snd[1][1:])}, 0, 1, {t}}}")
            else:
                items.append(f"{{{c_str(snd[0])}, {c_str(snd[1])}, {int(snd[2])}, 0, {t}}}")
        out.append(f"    {{{c_str(name)}, {len(sounds)}, {{" + ", ".join(items) + "}},")
    out.append("};")
    out.append(f"static const uint8_t LS_COUNT_V[LS_NCNT] = {{{', '.join(str(v) for v in count_v)}}};")
    out.append(f"static const uint8_t LS_COUNT_N[LS_NCNT] = {{{', '.join(str(v) for v in count_n)}}};   /* the count shown */")
    lins = [q["lin"] for q in qk.values() if q.get("lin")]
    chords = [q["chord"] for q in qk.values() if q.get("chord")]
    assert all(len(c) == 5 for c in chords), "a chord is 5 keys"
    out += ["/* a classic engine's activity map: each parameter from its value at C4 (lo) to C6 (hi), linear in the step;",
            " * a one-shot engine's presses: the mean gap at C4 (ms) and log2(gap at C6 / gap at C4) in Q16 (0 ms: held);",
            " * hold: 0 a 150 ms press, 1 held and turned over again at those gaps, 2 .. 255 a press (a call) of hold x 100 ms;",
            " * lin: 1 + its measured curve in LS_LIN (0: none); chord: 1 + the keys it holds in LS_CHORD (0: key 60) */",
            "typedef struct { const char *name; int16_t lo, hi; } ls_qp_t;",
            "typedef struct { const char *eng; uint8_t np, lin, hold, chord; ls_qp_t p[3]; uint32_t every_ms; int32_t every_oct_q16; } ls_quick_t;",
            "#define LS_CHORD_N 5u",
            f"#define LS_NCHORD {max(1, len(chords))}u",
            "static const uint8_t LS_CHORD[LS_NCHORD][LS_CHORD_N] = {   /* semitones over key 60 */",
            *["    {" + ", ".join(str(int(v)) for v in c) + "}," for c in (chords or [[0] * 5])],
            "};",
            f"#define LS_NLIN {max(1, len(lins))}u",
            "static const uint8_t LS_LIN[LS_NLIN][17] = {   /* the place (0 .. 127) at the keys' 0, 8 .. 120, 127 (tx_lin_tab) */"]
    for t in lins or [[0] * 17]:
        out.append("    {" + ", ".join(str(int(v)) for v in t) + "},")
    out += ["};", f"#define LS_NQUICK {len(qk)}u", "static const ls_quick_t LS_QUICK[LS_NQUICK] = {"]
    for eng, q in qk.items():
        ps = q.get("p", [])
        pt = ", ".join(f"{{{c_str(n)}, {int(lo)}, {int(hi)}}}" for n, lo, hi in ps) or "{0, 0, 0}"
        ev = q.get("every")
        ems, oct_ = (round(ev[0] * 1000), round(math.log2(ev[1] / ev[0]) * 65536)) if ev else (0, 0)
        li = 1 + lins.index(q["lin"]) if q.get("lin") else 0
        ch = 1 + chords.index(q["chord"]) if q.get("chord") else 0
        hold = 1 if q.get("turn") else round(q["press"] * 10) if q.get("press") else 0
        assert hold == 0 or 1 <= hold <= 255 and (hold == 1) == bool(q.get("turn")), eng
        out.append(f"    {{{c_str(eng)}, {len(ps)}, {li}, {hold}, {ch}, {{{pt}}}, {ems}u, {oct_}}},")
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print("FAIL  landscapes: firmware/src/landscapes.h differs from audition/app.js (make fw-landscapes)")
            return 1
        print("ok    landscapes: firmware/src/landscapes.h = audition/app.js")
        return 0
    OUT.write_text(text)
    print(f"-> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
